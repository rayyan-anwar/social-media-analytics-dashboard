"""Validate the analytics against planted ground truth over many seeds; test validation and measure runtime.

Usage: python scripts/evaluate.py [--seeds 20]     Author: Rayyan Anwar
"""
import argparse
import json
import platform
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.analytics import analyze, enrich, load_posts  # noqa: E402
from app.data import generate_posts  # noqa: E402


def detection(seeds: int) -> dict:
    spike_hit, false_spikes, trend_ok, hour1, hour3, tag_ok, acc = [], [], [], [], [], [], []
    for s in range(seeds):
        df, truth = generate_posts(3000, 60, s)
        clean, rep = load_posts(df)
        a = analyze(clean, rep)
        dates = [x["date"] for x in a["spikes"]]
        spike_hit.append(truth["spike_date"] in dates)
        false_spikes.append(len([d for d in dates if d != truth["spike_date"]]))
        trend_ok.append(a["trend"]["direction"] == truth["trend"])
        best = a["best_hours"]["best"]
        hour1.append(bool(best) and best[0] == truth["best_hour"])
        hour3.append(truth["best_hour"] in best)
        tag_ok.append(bool(a["hashtags_by_engagement"]) and a["hashtags_by_engagement"][0]["hashtag"] == truth["top_engagement_hashtag"])
        pred = enrich(clean)["sentiment"].to_numpy()
        acc.append(float((pred == df["true_sentiment"].to_numpy()).mean()))
    m = lambda v: float(np.mean(v))
    return {"seeds": seeds, "posts_per_dataset": 3000, "days": 60,
            "spike_recall": m(spike_hit), "false_spike_days_per_dataset": m(false_spikes),
            "trend_direction_correct": m(trend_ok), "best_hour_top1": m(hour1), "best_hour_in_top3": m(hour3),
            "top_engagement_hashtag_correct": m(tag_ok), "sentiment_accuracy_mean": m(acc),
            "sentiment_accuracy_sd": float(np.std(acc, ddof=1)) if len(acc) > 1 else 0.0}


def validation_check() -> dict:
    df, _ = generate_posts(2000, 40, 99)
    df = df.copy()
    df["timestamp"] = df["timestamp"].astype(object)
    df.loc[df.index[:50], "timestamp"] = "not a date"
    df.loc[df.index[50:90], "likes"] = -5
    df["shares"] = df["shares"].astype(object)
    df.loc[df.index[90:120], "shares"] = "abc"
    dups = df.iloc[200:230].copy()
    df = __import__("pandas").concat([df, dups], ignore_index=True)
    _, rep = load_posts(df)
    exp = {"invalid_timestamp": 50, "invalid_or_negative_counts": 70, "duplicate_post_id": 30}
    return {"injected": exp, "reported": rep["dropped"], "exact_match": rep["dropped"] == exp, "rows_kept": rep["rows_kept"],
            "expected_rows_kept": 2030 - 150}


def runtime() -> dict:
    out = {}
    for n in (10_000, 50_000):
        df, _ = generate_posts(n, 90, 0)
        t0 = time.perf_counter()
        clean, rep = load_posts(df)
        analyze(clean, rep)
        out[str(n)] = round(time.perf_counter() - t0, 2)
    return {"load_and_analyze_seconds": out}


def to_md(r):
    d, v, rt, e = r["detection"], r["validation"], r["runtime"], r["environment"]
    return "\n".join([
        "# Results (generated by `scripts/evaluate.py`)", "",
        f"- Created (UTC): {r['created_utc']}; machine: {e['platform']}; Python {e['python']}; CPUs {e['cpu_count']}", "",
        f"## Recovery of planted signals ({d['seeds']} seeded datasets, {d['posts_per_dataset']} posts over {d['days']} days)", "",
        "| Check | Result |", "|---|---:|",
        f"| Spike day detected (recall) | {d['spike_recall']:.2f} |",
        f"| False spike days per dataset | {d['false_spike_days_per_dataset']:.2f} |",
        f"| Trend direction correct | {d['trend_direction_correct']:.2f} |",
        f"| Best hour ranked first | {d['best_hour_top1']:.2f} |",
        f"| Best hour within top 3 | {d['best_hour_in_top3']:.2f} |",
        f"| Highest-engagement hashtag correct | {d['top_engagement_hashtag_correct']:.2f} |",
        f"| Lexicon sentiment accuracy vs generator labels | {d['sentiment_accuracy_mean']:.3f} ± {d['sentiment_accuracy_sd']:.3f} |", "",
        "Planted-signal recovery is a check that the code computes what it claims on controlled data; it is not evidence about real social platforms. "
        "The sentiment generator and lexicon share an author, so that accuracy is a sanity check only.", "",
        "## Validation of corrupted input", "",
        f"Injected {v['injected']}; reported {v['reported']}; exact match: {v['exact_match']}; rows kept {v['rows_kept']} (expected {v['expected_rows_kept']}).", "",
        "## Runtime (load + validate + analyse)", "", "| Rows | Seconds |", "|---:|---:|"] +
        [f"| {k} | {x} |" for k, x in rt["load_and_analyze_seconds"].items()]) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--seeds", type=int, default=20)
    a = ap.parse_args()
    r = {"created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
         "environment": {"platform": platform.platform(), "python": sys.version.split()[0], "cpu_count": __import__("os").cpu_count()},
         "detection": detection(a.seeds), "validation": validation_check(), "runtime": runtime()}
    (ROOT / "results").mkdir(exist_ok=True)
    (ROOT / "results" / "results.json").write_text(json.dumps(r, indent=2))
    (ROOT / "results" / "RESULTS.md").write_text(to_md(r))
    print(to_md(r))


if __name__ == "__main__":
    main()
